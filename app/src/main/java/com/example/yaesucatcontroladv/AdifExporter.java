package com.example.yaesucatcontroladv;

import android.content.ContentResolver;
import android.content.ContentValues;
import android.content.Context;
import android.net.Uri;
import android.os.Build;
import android.os.Environment;
import android.provider.MediaStore;

import androidx.core.content.FileProvider;

import java.io.BufferedReader;
import java.io.File;
import java.io.FileOutputStream;
import java.io.InputStream;
import java.io.InputStreamReader;
import java.io.OutputStream;
import java.nio.charset.StandardCharsets;
import java.text.SimpleDateFormat;
import java.util.Date;
import java.util.List;
import java.util.Locale;

public class AdifExporter {

    private static final String PROGRAM_ID = "YaesuCatControlADV";
    private static final String ADIF_VERSION = "3.1.4";

    public static class RezultatImportAdif {
        public int qsoImportate = 0;
        public int qsoDuplicate = 0;
        public boolean validFormat = false;
    }

    /**
     * Generează conținutul ADIF și îl salvează într-un fișier temporar în cache
     * pentru a fi partajat (Share) către Email sau alte aplicații.
     */
    public static Uri getShareableAdifUri(Context context, QsoDbHelper dbHelper) throws Exception {
        String continut = genereazaContinutAdif(dbHelper);
        SimpleDateFormat sdf = new SimpleDateFormat("yyyyMMdd_HHmm", Locale.US);
        String numeFisier = "YaesuLog_" + sdf.format(new Date()) + ".adi";

        File cacheDir = new File(context.getCacheDir(), "shared_logs");
        if (!cacheDir.exists()) cacheDir.mkdirs();

        File file = new File(cacheDir, numeFisier);
        try (FileOutputStream fos = new FileOutputStream(file)) {
            fos.write(continut.getBytes(StandardCharsets.UTF_8));
        }

        return FileProvider.getUriForFile(context, 
                "com.example.yaesucatcontroladv.fileprovider", file);
    }

    private static String genereazaContinutAdif(QsoDbHelper dbHelper) {
        StringBuilder sb = new StringBuilder();
        // Header ADIF standard
        sb.append("Generated by ").append(PROGRAM_ID).append("\n");
        sb.append("<ADIF_VER:").append(ADIF_VERSION.length()).append(">").append(ADIF_VERSION).append("\n");
        sb.append("<PROGRAMID:").append(PROGRAM_ID.length()).append(">").append(PROGRAM_ID).append("\n");
        sb.append("<EOH>\n\n");

        List<QsoDbHelper.Qso> qsouri = dbHelper.getToateQsourile();
        for (QsoDbHelper.Qso q : qsouri) {
            appendTag(sb, "CALL", q.call);
            appendTag(sb, "QSO_DATE", q.qsoDate);
            appendTag(sb, "TIME_ON", q.timeOn);
            appendTag(sb, "BAND", q.band);
            appendTag(sb, "FREQ", q.freq);
            appendTag(sb, "MODE", q.mode);
            appendTag(sb, "RST_SENT", q.rstSent);
            appendTag(sb, "RST_RCVD", q.rstRcvd);
            appendTag(sb, "NAME", q.name);
            appendTag(sb, "QTH", q.qth);
            appendTag(sb, "GRIDSQUARE", q.gridsquare);
            appendTag(sb, "COMMENT", q.comment);
            appendTag(sb, "TX_PWR", q.power);
            appendTag(sb, "OPERATOR", q.myCall);
            appendTag(sb, "MY_GRIDSQUARE", q.myGridsquare);
            sb.append("<EOR>\n");
        }
        return sb.toString();
    }

    // ============================================================
    // EXPORT ADIF
    // ============================================================
    public static String exportaAdif(Context context, QsoDbHelper dbHelper) throws Exception {
        String continut = genereazaContinutAdif(dbHelper);
        SimpleDateFormat sdf = new SimpleDateFormat("yyyyMMdd_HHmmss", Locale.US);
        String numeFisier = PROGRAM_ID + "_" + sdf.format(new Date()) + ".adi";

        if (Build.VERSION.SDK_INT >= Build.VERSION_CODES.Q) {
            salveazaAdifMediaStore(context, numeFisier, continut);
        } else {
            salveazaAdifLegacy(numeFisier, continut);
        }
        return numeFisier;
    }

    private static void appendTag(StringBuilder sb, String tag, String value) {
        if (value != null && !value.trim().isEmpty()) {
            sb.append("<").append(tag).append(":").append(value.length()).append(">").append(value).append("\n");
        }
    }
    @androidx.annotation.RequiresApi(android.os.Build.VERSION_CODES.Q)
    private static void salveazaAdifMediaStore(Context context, String numeFisier, String continut) throws Exception {
        ContentResolver resolver = context.getContentResolver();
        ContentValues values = new ContentValues();
        values.put(MediaStore.Downloads.DISPLAY_NAME, numeFisier);
        values.put(MediaStore.Downloads.MIME_TYPE, "text/plain");
        values.put(MediaStore.Downloads.RELATIVE_PATH, Environment.DIRECTORY_DOWNLOADS + "/" + PROGRAM_ID);
        Uri uri = resolver.insert(MediaStore.Downloads.EXTERNAL_CONTENT_URI, values);
        if (uri == null) throw new Exception("Could not create ADIF file.");
        try (OutputStream out = resolver.openOutputStream(uri)) {
            if (out == null) throw new Exception("Could not open ADIF file.");
            out.write(continut.getBytes(StandardCharsets.UTF_8));
        }
    }

    private static void salveazaAdifLegacy(String numeFisier, String continut) throws Exception {
        File dir = new File(Environment.getExternalStoragePublicDirectory(Environment.DIRECTORY_DOWNLOADS), PROGRAM_ID);
        if (!dir.exists()) dir.mkdirs();
        File fisier = new File(dir, numeFisier);
        try (FileOutputStream fos = new FileOutputStream(fisier)) {
            fos.write(continut.getBytes(StandardCharsets.UTF_8));
        }
    }

    // ============================================================
    // IMPORT ADIF (Doar fișiere proprii + Anti-duplicat)
    // ============================================================
    public static RezultatImportAdif importaAdif(Context context, QsoDbHelper dbHelper, Uri uri) throws Exception {
        RezultatImportAdif rezultat = new RezultatImportAdif();

        StringBuilder continut = new StringBuilder();
        try (InputStream in = context.getContentResolver().openInputStream(uri)) {
            if (in == null) throw new Exception("Invalid file.");
            BufferedReader reader = new BufferedReader(new InputStreamReader(in, StandardCharsets.UTF_8));
            String linie;
            while ((linie = reader.readLine()) != null) {
                continut.append(linie).append("\n");
            }
        }

        String text = continut.toString();

        // Verificare obligatorie PROGRAMID
        if (!text.contains("<PROGRAMID:" + PROGRAM_ID.length() + ">" + PROGRAM_ID)) {
            return rezultat; // validFormat rămâne false
        }
        rezultat.validFormat = true;

        // Parsare după <EOH>
        int eohIndex = text.indexOf("<EOH>");
        if (eohIndex == -1) return rezultat;

        String body = text.substring(eohIndex + 5);
        String[] records = body.split("<EOR>");

        for (String record : records) {
            if (record.trim().isEmpty()) continue;

            QsoDbHelper.Qso q = new QsoDbHelper.Qso();
            q.call = extractTag(record, "CALL");
            q.qsoDate = extractTag(record, "QSO_DATE");
            q.timeOn = extractTag(record, "TIME_ON");
            q.band = extractTag(record, "BAND");
            q.freq = extractTag(record, "FREQ");
            q.mode = extractTag(record, "MODE");
            q.rstSent = extractTag(record, "RST_SENT");
            q.rstRcvd = extractTag(record, "RST_RCVD");
            q.name = extractTag(record, "NAME");
            q.qth = extractTag(record, "QTH");
            q.gridsquare = extractTag(record, "GRIDSQUARE");
            q.comment = extractTag(record, "COMMENT");
            q.power = extractTag(record, "TX_PWR");
            q.myCall = extractTag(record, "OPERATOR");
            q.myGridsquare = extractTag(record, "MY_GRIDSQUARE");

            if (q.call == null || q.call.isEmpty()) continue;

            // Anti-duplicat: verificăm CALL + DATE + TIME
            if (dbHelper.existaQso(q.call, q.qsoDate, q.timeOn)) {
                rezultat.qsoDuplicate++;
            } else {
                dbHelper.insereazaQso(q);
                rezultat.qsoImportate++;
            }
        }
        return rezultat;
    }

    private static String extractTag(String record, String tag) {
        String search = "<" + tag + ":";
        int start = record.indexOf(search);
        if (start == -1) return "";

        int lenStart = start + search.length();
        int lenEnd = record.indexOf(">", lenStart);
        if (lenEnd == -1) return "";

        try {
            int length = Integer.parseInt(record.substring(lenStart, lenEnd).trim());
            int valStart = lenEnd + 1;
            if (valStart + length > record.length()) return "";
            return record.substring(valStart, valStart + length).trim();
        } catch (Exception e) {
            return "";
        }
    }
}